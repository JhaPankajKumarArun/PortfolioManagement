import assert from 'node:assert/strict';
import {buildSourceRegistry,allowedDownload} from '../scripts/amc-sources.mjs';
const registry={amcs:[{name:'Example Mutual Fund',codes:['123456']},{name:'Other Mutual Fund',codes:['123457']}]};
const source={names:['Example Mutual Fund'],hosts:['example.com'],formats:['xlsx'],status:'experimental'};
const rows=buildSourceRegistry(registry,[source]);
assert.equal(rows[0].status,'experimental');
assert.equal(rows[1].status,'unconfigured');
assert.equal(buildSourceRegistry(registry,[source,source])[0].status,'ambiguous');
assert.equal(allowedDownload(source,'https://example.com/portfolio.xlsx'),true);
assert.equal(allowedDownload(source,'https://example.com.evil.test/portfolio.xlsx'),false);
assert.equal(allowedDownload(source,'http://example.com/portfolio.xlsx'),false);
assert.equal(allowedDownload(source,'https://example.com/portfolio.exe'),false);
console.log('AMC source registry tests passed');
