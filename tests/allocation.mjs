import assert from 'node:assert/strict';
import {allocationPlan} from '../js/engines/allocation.mjs';
const h=[{type:'mf',value:80000},{type:'stock',value:20000}],t={mf:60,stock:40,other:0};
const p=allocationPlan(h,t,20000);
assert.equal(p.rows[0].add,0);
assert.equal(p.rows[1].add,20000);
assert.equal(p.rows[0].drift,20);
assert.ok(Math.abs(p.rows[1].projected-100/3)<1e-9);
assert.equal(allocationPlan(h,{mf:60,stock:30,other:0},100),null);
assert.equal(allocationPlan(h,t,-1),null);
assert.equal(allocationPlan([{type:'mf',value:NaN}],t,100),null);
const q=allocationPlan([],t,1000);
assert.equal(q.rows[0].add,600);
assert.equal(q.rows[1].add,400);
assert.equal(allocationPlan([],t,0).rows[0].weight,null);
const r=allocationPlan(h,t,100000);
assert.ok(Math.abs(r.rows.reduce((s,x)=>s+x.add,0)-100000)<1e-8);
assert.ok(r.rows.every(x=>Math.abs(x.projected-x.target)<1e-8));
console.log('Allocation fixtures passed');
